const fs = require("fs");

const file = "app/api/autopilot/run/route.ts";
const data = fs.readFileSync(file);

let startToken = Buffer.from(
  "    /*\r\n     * SPEED BOOSTER V1 - CREATIVE SPLIT"
);

if (data.indexOf(startToken) === -1) {
  startToken = Buffer.from(
    "    /*\n     * SPEED BOOSTER V1 - CREATIVE SPLIT"
  );
}

const endToken = Buffer.from(
  "    const postprocessStartedAt"
);

const start = data.indexOf(startToken);
const end = data.indexOf(endToken, start);

if (start < 0 || end < 0 || end <= start) {
  throw new Error("Creative-Block nicht gefunden.");
}

const oldBlock = data.subarray(start, end);

const required = [
  "const creativeStartedAt",
  "const creativeContent",
  "const creativeResponse",
  "inserat_ai_autopilot_creative",
  "parsed.imageAnalyses",
  "parsed.variants"
];

for (const marker of required) {
  if (!oldBlock.includes(Buffer.from(marker))) {
    throw new Error("Marker fehlt: " + marker);
  }
}

const nl = oldBlock.includes(Buffer.from("\r\n"))
  ? "\r\n"
  : "\n";

const replacement = [
'    /*',
'     * FAST READY V2 - VISION ONLY',
'     *',
'     * Analysiert nur Bilder. Keine CORE-Abhaengigkeit.',
'     * Dadurch kann VISION danach parallel zu CORE laufen.',
'     */',
'    const creativeStartedAt =',
'      Date.now();',
'',
'    const creativeContent: Array<',
'      Record<string, unknown>',
'    > = [',
'      {',
'        type: "input_text",',
'        text:',
'          "Analysiere ausschliesslich die bereitgestellten Immobilienbilder. " +',
'          "Erfinde keine nicht sichtbaren Fakten. " +',
'          "Gib fuer jedes Bild imageIndex, Raumtyp, sichtbaren Zustand und maximal fuenf sichtbare Merkmale zurueck. " +',
'          "imageIndex beginnt bei 1 und entspricht exakt der Reihenfolge der Bilder.",',
'      },',
'    ];',
'',
'    registeredImages.forEach(',
'      (image, index) => {',
'        creativeContent.push({',
'          type: "input_text",',
'          text:',
'            `Bild ${index + 1}`,',
'        });',
'',
'        creativeContent.push({',
'          type: "input_image",',
'          image_url:',
'            image.url,',
'          detail: "low",',
'        });',
'      }',
'    );',
'',
'    let visionImageAnalyses: ImageAnalysis[] =',
'      [];',
'',
'    if (registeredImages.length > 0) {',
'      const creativeResponse =',
'        await fetch(',
'          "https://api.openai.com/v1/responses",',
'          {',
'            method: "POST",',
'',
'            headers: {',
'              Authorization:',
'                `Bearer ${process.env.OPENAI_API_KEY}`,',
'',
'              "Content-Type":',
'                "application/json",',
'            },',
'',
'            body: JSON.stringify({',
'              model:',
'                process.env',
'                  .OPENAI_AUTOPILOT_MODEL ||',
'                "gpt-4.1-mini",',
'',
'              store: false,',
'',
'              max_output_tokens:',
'                900,',
'',
'              input: [',
'                {',
'                  role: "user",',
'                  content:',
'                    creativeContent,',
'                },',
'              ],',
'',
'              text: {',
'                format: {',
'                  type: "json_schema",',
'',
'                  name:',
'                    "inserat_ai_autopilot_vision",',
'',
'                  strict: true,',
'',
'                  schema: {',
'                    type: "object",',
'',
'                    additionalProperties:',
'                      false,',
'',
'                    properties: {',
'                      imageAnalyses: {',
'                        type: "array",',
'',
'                        items: {',
'                          type: "object",',
'',
'                          additionalProperties:',
'                            false,',
'',
'                          properties: {',
'                            imageIndex: {',
'                              type: "integer",',
'                            },',
'',
'                            room: {',
'                              type: "string",',
'                            },',
'',
'                            condition: {',
'                              type: "string",',
'                            },',
'',
'                            visibleFacts: {',
'                              type: "array",',
'',
'                              items: {',
'                                type: "string",',
'                              },',
'',
'                              maxItems: 5,',
'                            },',
'                          },',
'',
'                          required: [',
'                            "imageIndex",',
'                            "room",',
'                            "condition",',
'                            "visibleFacts",',
'                          ],',
'                        },',
'                      },',
'                    },',
'',
'                    required: [',
'                      "imageAnalyses",',
'                    ],',
'                  },',
'                },',
'              },',
'            }),',
'          }',
'        );',
'',
'      const creativeRawText =',
'        await creativeResponse.text();',
'',
'      let creativePayload: unknown =',
'        null;',
'',
'      try {',
'        creativePayload =',
'          creativeRawText',
'            ? JSON.parse(',
'                creativeRawText',
'              )',
'            : null;',
'      } catch {',
'        creativePayload =',
'          creativeRawText;',
'      }',
'',
'      if (!creativeResponse.ok) {',
'        console.error(',
'          "[autopilot/run] VISION_OPENAI_DIAGNOSTIC " +',
'            JSON.stringify({',
'              status:',
'                creativeResponse.status,',
'',
'              requestId:',
'                creativeResponse.headers.get(',
'                  "x-request-id"',
'                ),',
'',
'              payload:',
'                creativePayload,',
'            })',
'        );',
'',
'        throw new Error(',
'          "Inserat-AI konnte die Bilder nicht analysieren."',
'        );',
'      }',
'',
'      const creativeOutputText =',
'        extractOutputText(',
'          creativePayload',
'        );',
'',
'      if (!creativeOutputText) {',
'        throw new Error(',
'          "Inserat-AI hat kein Vision-Ergebnis zurueckgegeben."',
'        );',
'      }',
'',
'      let creativeParsed: {',
'        imageAnalyses:',
'          ImageAnalysis[];',
'      };',
'',
'      try {',
'        creativeParsed =',
'          JSON.parse(',
'            creativeOutputText',
'          ) as {',
'            imageAnalyses:',
'              ImageAnalysis[];',
'          };',
'      } catch {',
'        throw new Error(',
'          "Das Vision-Ergebnis hatte kein gueltiges JSON-Format."',
'        );',
'      }',
'',
'      visionImageAnalyses =',
'        Array.isArray(',
'          creativeParsed.imageAnalyses',
'        )',
'          ? creativeParsed.imageAnalyses',
'          : [];',
'    }',
'',
'    parsed.imageAnalyses =',
'      visionImageAnalyses;',
'',
'    /*',
'     * Schnelle lokale Kompatibilitaetsvarianten.',
'     * Die langen AI-Texte blockieren READY nicht mehr.',
'     */',
'    const fastTitleParts = [',
'      safeString(',
'        parsed.propertyType,',
'        80',
'      ),',
'      safeString(',
'        parsed.location,',
'        80',
'      ),',
'    ].filter(Boolean);',
'',
'    const fastTitle =',
'      fastTitleParts.join(" in ") ||',
'      "Immobilienangebot";',
'',
'    const fastTextParts = [',
'      safeString(',
'        parsed.summary,',
'        4000',
'      ),',
'',
'      Array.isArray(',
'        parsed.highlights',
'      )',
'        ? parsed.highlights',
'            .map((item) =>',
'              safeString(',
'                item,',
'                300',
'              )',
'            )',
'            .filter(Boolean)',
'            .join(" ")',
'        : "",',
'    ].filter(Boolean);',
'',
'    const fastText =',
'      fastTextParts.join("\\n\\n") ||',
'      fastTitle;',
'',
'    parsed.variants = [',
'      {',
'        title: fastTitle,',
'        text: fastText,',
'      },',
'      {',
'        title: fastTitle,',
'        text: fastText,',
'      },',
'      {',
'        title: fastTitle,',
'        text: fastText,',
'      },',
'    ];',
'',
'    const creativeDurationMs =',
'      Date.now() -',
'      creativeStartedAt;',
'',
'    console.info(',
'      "[AUTOPILOT_VISION_TIMING]",',
'      {',
'        listingId:',
'          listing.id,',
'',
'        imageCount:',
'          registeredImages.length,',
'',
'        durationMs:',
'          creativeDurationMs,',
'',
'        durationSeconds:',
'          Number(',
'            (',
'              creativeDurationMs /',
'              1000',
'            ).toFixed(2)',
'          ),',
'      }',
'    );',
'',
''
].join(nl);

const output = Buffer.concat([
  data.subarray(0, start),
  Buffer.from(replacement, "ascii"),
  data.subarray(end)
]);

fs.writeFileSync(file, output);

console.log("VISION-only Patch eingesetzt.");
console.log("Alter Block:", oldBlock.length, "Bytes");
console.log(
  "Neuer Block:",
  Buffer.byteLength(replacement, "ascii"),
  "Bytes"
);
